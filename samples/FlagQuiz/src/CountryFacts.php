/**
 * The things a country is known for besides its flag and its capital: the
 * landmarks people travel to see, the rivers and mountain ranges and big
 * waters that shape it, and how many people live there. Five more
 * {@see Attribute}s to show or ask for, and this is where their content lives
 * — keyed by ISO-2 code and built once, the way {@see FlagTraits} and
 * {@see CountryPoints} are.
 *
 * Not every country has every fact, and that is the point rather than a gap to
 * be filled: Malta has no river, Botswana no mountain range, Qatar neither. A
 * country with nothing to say about the attribute in play is simply left out
 * of the round ({@see Attribute::hasData()}), so a question is never asked of
 * a country that cannot answer it.
 *
 * Each list is ordered best-known first, and every entry in it is accepted as
 * an answer — asked for a river in Egypt there is one, asked for one in Sudan
 * the Blue Nile will do as well as the Nile.
 */
final class CountryFacts
{
    /**
     * Below this the "nearest 100 000" the population question is marked to
     * cannot tell one country from another: every microstate answers 0.0 or
     * 0.1 and the question stops being about the country. Those countries
     * carry no population fact at all (see {@see hasPopulation()}), which
     * keeps them out of population rounds while leaving their other facts in
     * play.
     */
    public const POPULATION_FLOOR = 100_000;

    /** The unit the population question is asked and answered in. */
    public const PER_MILLION = 1_000_000;

    /** The precision it is marked to: 0.1 million, i.e. 100 000 people. */
    public const PER_STEP = 100_000;

    /**
     * How many landmarks a country is known by here.
     *
     * The lists below run best-known first, and are cut to this. Two is what a
     * country is actually famous for: France is the Eiffel Tower and the
     * Louvre, and by the time a list reaches its fifth entry it has left the
     * things everyone has heard of and is naming places you would have to have
     * been there to know. On the map that difference is the difference between
     * a few pins that say something and a country buried under its own labels.
     */
    public const MAJOR_LANDMARKS = 2;

    /** @var string[] the best-known, cut to {@see MAJOR_LANDMARKS} */
    public readonly array $landmarks;

    /**
     * @param int      $population mid-2024 estimate, 0 where none is carried
     * @param string[] $landmarks  what people go there to see, best-known first
     * @param string[] $rivers     the major rivers running through it
     * @param string[] $mountains  the mountain ranges and massifs in it
     * @param string[] $lakes      big lakes, and the dams that made some of them
     */
    public function __construct(
        public readonly int $population = 0,
        array $landmarks = [],
        public readonly array $rivers = [],
        public readonly array $mountains = [],
        public readonly array $lakes = [],
    ) {
        // Cut here rather than in the table below, so the table stays a record
        // of what each country is known for and this stays the one place the
        // cut is decided.
        $this->landmarks = array_slice($landmarks, 0, self::MAJOR_LANDMARKS);
    }

    /** Facts for a country code, or an empty set when none are carried. */
    public static function for(string $code): self
    {
        return self::map()[strtolower($code)] ?? new self();
    }

    /** Whether this country's population is worth asking to the nearest 100 000. */
    public function hasPopulation(): bool
    {
        return $this->population >= self::POPULATION_FLOOR;
    }

    /**
     * The population as the question puts it: in millions, to the one decimal
     * place the answer is marked against. What is shown and what is accepted
     * are the same number by construction.
     */
    public function populationLabel(): string
    {
        return number_format($this->populationSteps() / 10, 1) . ' million';
    }

    /**
     * The population in whole 100 000s — the unit the answer is judged in, so
     * that judging is an integer comparison rather than two floats hoping to
     * land on the same value.
     */
    public function populationSteps(): int
    {
        return (int)round($this->population / self::PER_STEP);
    }

